"""Build results/summary.md and results/summary.csv from the saved results. Every reported number comes from here."""
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from kitbench import stats  # noqa: E402
from kitbench.templates import CONDITIONS  # noqa: E402


def render(rows: list[dict]) -> tuple[str, list[dict]]:
    """The markdown summary and the csv rows."""
    lines = ["# Results", "", "Generated by scripts/summarize.py from results/. Do not edit by hand.", ""]
    table = []
    for cond in [c for c in ["B", "A", "C", "A_alt"] if c in CONDITIONS]:
        models = stats.model_table(rows, cond)
        if not models:
            continue
        lines += [f"## Condition {cond}: {CONDITIONS[cond]}", "",
                  "| Model | Trials | Full-pass rate | pass^k (kits where every trial passed) | Mean score | Output tokens (mean) | Seconds (mean) | Cost (USD) |",
                  "|---|---|---|---|---|---|---|---|"]
        for t in models:
            c = "n/a" if t["cost_usd"] is None else f"{t['cost_usd']:.2f}"
            lines.append(f"| {t['model']} | {t['trials']} | {t['passes']}/{t['trials']} ({100 * t['pass_rate']:.0f}%) | "
                         f"{t['passk']}/{t['kits']} | {t['mean_score']:.2f} | {t['mean_output_tokens']:,.0f} | {t['mean_seconds']:.0f} | {c} |")
            table.append({"condition": cond, **{k: (round(v, 4) if isinstance(v, float) else v) for k, v in t.items()}})
        grid = stats.kit_grid(rows, cond)
        names = [t["model"] for t in models]
        lines += ["", "Per kit (full passes / trials):", "", "| Kit | " + " | ".join(names) + " |", "|---" * (len(names) + 1) + "|"]
        for kit, cells in grid.items():
            lines.append(f"| {kit} | " + " | ".join(f"{cells[m]['passes']}/{cells[m]['trials']}" if m in cells else "-" for m in names) + " |")
        fails = stats.failure_breakdown(rows, cond)
        total = {}
        for per in fails.values():
            for k, v in per.items():
                total[k] = total.get(k, 0) + v
        lines += ["", "Failure types:", ""] + [f"- {k}: {v}" for k, v in sorted(total.items(), key=lambda kv: -kv[1])] + [""]
    errors = [r for r in rows if r.get("status") != "ok"]
    lines += ["## Most common mistakes", "", "| Kit | Failed check | Trials | Median error |", "|---|---|---|---|"]
    for m in stats.top_mistakes(rows):
        lines.append(f"| {m['kit']} | {m['check']} | {m['trials']} | {m['median_err']} |")
    lines += ["", f"API errors excluded from all numbers: {len(errors)}", ""]
    return "\n".join(lines), table


def main() -> None:
    """Write (or with --check, verify) results/summary.md and summary.csv."""
    text, table = render(stats.load(ROOT / "results"))
    if "--check" in sys.argv:
        same = (ROOT / "results" / "summary.md").read_text() == text
        print("summary.md matches the results" if same else "summary.md is out of date: run scripts/summarize.py")
        sys.exit(0 if same else 1)
    (ROOT / "results" / "summary.md").write_text(text)
    with open(ROOT / "results" / "summary.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(table[0]) if table else ["condition"])
        w.writeheader()
        w.writerows(table)
    print(text)


if __name__ == "__main__":
    main()
